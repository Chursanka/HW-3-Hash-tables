def easy_task(n, x, y):
    mini = 0
    maxi = n * max(x, y)
    while mini < maxi:
        mid = (mini + maxi) // 2
        cnt = mid//x + mid//y
        if cnt >= n:
            maxi = mid
        else:
            mini = mid + 1
    return mini

